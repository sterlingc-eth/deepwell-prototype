/**
 * Runs the 50-question evaluation against the mock answer service.
 *
 *   npm run eval            → pass/fail per question, non-zero exit on any failure
 *   npm run eval -- --doc   → also regenerate docs/EVAL_QUESTIONS.md
 *   npm run eval -- --verbose
 */
import { writeFileSync } from 'node:fs';
import { buildDocuments, buildEntities } from '../src/domains/hvac/seed';
import { hvacSchema } from '../src/domains/hvac/schema';
import { answerSync } from '../src/services/answerService.mock';
import type { GraphSnapshot } from '../src/core/entityGraph';
import { EVAL_NOW, EVAL_QUESTIONS, type EvalCase } from '../src/eval/questions';

const { docs, batches, conflicts } = buildDocuments();
const g: GraphSnapshot = {
  schema: hvacSchema,
  entities: Object.fromEntries(buildEntities().map((e) => [e.id, e])),
  docs: Object.fromEntries(docs.map((d) => [d.id, d])),
  batches: Object.fromEntries(batches.map((b) => [b.id, b])),
  conflicts: Object.fromEntries(conflicts.map((c) => [c.id, c])),
};

const verbose = process.argv.includes('--verbose');
const writeDoc = process.argv.includes('--doc');

interface Result {
  c: EvalCase;
  pass: boolean;
  failures: string[];
  text: string;
}

function run(c: EvalCase): Result {
  const a = answerSync(c.q, g, { now: EVAL_NOW, includeUnverified: c.includeUnverified ?? false });
  const failures: string[] = [];
  const text = a.text.toLowerCase();
  const factBlob = a.facts.map((f) => `${f.label} ${f.value}`).join(' | ');
  if (a.kind !== c.expect.kind) failures.push(`kind ${a.kind} ≠ ${c.expect.kind}`);
  if (c.expect.entityId && a.entityId !== c.expect.entityId) failures.push(`entity ${a.entityId ?? '—'} ≠ ${c.expect.entityId}`);
  for (const t of c.expect.text ?? []) if (!text.includes(t.toLowerCase())) failures.push(`text missing “${t}”`);
  for (const t of c.expect.notText ?? []) if (text.includes(t.toLowerCase())) failures.push(`text must not contain “${t}”`);
  for (const f of c.expect.facts ?? []) if (!factBlob.includes(f)) failures.push(`facts missing “${f}”`);
  if (c.expect.minVerified !== undefined && a.verifiedCount < c.expect.minVerified) failures.push(`verified ${a.verifiedCount} < ${c.expect.minVerified}`);
  if (c.expect.unverified !== undefined && a.unverifiedCount !== c.expect.unverified) failures.push(`unverified ${a.unverifiedCount} ≠ ${c.expect.unverified}`);
  // Invariant: no fact without a source
  for (const f of a.facts) if (!f.sources.length) failures.push(`fact “${f.label}” has no source`);
  if (a.kind === 'answer' && a.sources.length === 0) failures.push('answer has no sources');
  return { c, pass: failures.length === 0, failures, text: a.text };
}

const results = EVAL_QUESTIONS.map(run);
const passed = results.filter((r) => r.pass).length;

for (const r of results) {
  const mark = r.pass ? '✓' : '✗';
  const flag = r.c.includeUnverified ? ' [incl. unverified]' : '';
  console.log(`${mark} ${String(r.c.id).padStart(2)}  ${r.c.q}${flag}`);
  if (!r.pass || verbose) {
    console.log(`     → ${r.text}`);
    for (const f of r.failures) console.log(`     ✗ ${f}`);
  }
}
console.log(`\n${passed}/${results.length} passed`);

if (writeDoc) {
  const groups = Array.from(new Set(EVAL_QUESTIONS.map((c) => c.group)));
  const lines: string[] = [
    '# Evaluation questions',
    '',
    'The acceptance test for the Ask interface. Source of truth is `src/eval/questions.ts`; this file is generated by `npm run eval -- --doc`.',
    '',
    `Clock is fixed at **${EVAL_NOW.toISOString().slice(0, 10)}**. Answers draw on Verified documents only unless marked *incl. unverified*.`,
    '',
    `**Result on last run: ${passed}/${results.length} passed.** Publish this number to the customer; below 95% we keep working before go-live.`,
    '',
  ];
  for (const group of groups) {
    lines.push(`## ${group}`, '');
    lines.push('| # | Question | Must contain | Answer |', '|---|---|---|---|');
    for (const r of results.filter((x) => x.c.group === group)) {
      const must = [
        r.c.expect.kind === 'no-answer' ? 'honest no-answer' : '',
        r.c.expect.entityId ? `entity ${r.c.expect.entityId}` : '',
        ...(r.c.expect.text ?? []).map((t) => `“${t}”`),
        ...(r.c.expect.facts ?? []).map((t) => `fact ${t}`),
        r.c.expect.unverified !== undefined ? `${r.c.expect.unverified} unverified held back` : '',
      ]
        .filter(Boolean)
        .join('; ');
      const q = `${r.c.q}${r.c.includeUnverified ? ' *(incl. unverified)*' : ''}`;
      lines.push(`| ${r.c.id} | ${q.replace(/\|/g, '\\|')} | ${must.replace(/\|/g, '\\|')} | ${r.pass ? '✓' : '✗'} ${r.text.replace(/\|/g, '\\|')} |`);
    }
    lines.push('');
  }
  writeFileSync('docs/EVAL_QUESTIONS.md', lines.join('\n'));
  console.log('wrote docs/EVAL_QUESTIONS.md');
}

process.exit(passed === results.length ? 0 : 1);
